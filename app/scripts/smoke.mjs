// Opens the built web app and checks the first screens render without errors.
import { chromium } from 'playwright';
const out = [];
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 390, height: 844 } });
const errs = [];
p.on('pageerror', e => errs.push('pageerror: ' + e.message));
p.on('console', m => { if (m.type() === 'error') errs.push('console: ' + m.text()); });
const body = async () => (await p.textContent('body')).replace(/\s+/g, ' ');
await p.goto('http://localhost:4000/', { waitUntil: 'networkidle' });
await p.waitForTimeout(1500);
out.push('url after load: ' + p.url());
const t = await body();
out.push('has LINE: ' + t.includes('ดำเนินการต่อด้วย LINE') + ' · has Google: ' + t.includes('ดำเนินการต่อด้วย Google'));
await p.getByText('ใช้อีเมลและรหัสผ่าน').click();
await p.getByLabel('อีเมล').fill('nobody@example.com');
await p.getByLabel('รหัสผ่าน').fill('wrongpass1');
await p.getByRole('button', { name: 'เข้าสู่ระบบ' }).last().click();
await p.waitForTimeout(3000);
out.push('wrong login message: ' + (await body()).includes('อีเมลหรือรหัสผ่านไม่ถูก'));
await p.getByText('สมัครด้วยอีเมล').click();
await p.waitForTimeout(800);
out.push('signup url: ' + p.url());
await p.getByLabel('รหัสประเทศ ไทย +66').click();
await p.getByText('สิงคโปร์').click();
out.push('country switched: ' + (await body()).includes('+65'));
await p.getByRole('button', { name: 'สมัครใช้งาน' }).last().click();
await p.waitForTimeout(500);
out.push('signup validation: ' + (await body()).match(/ใส่ชื่อ|รูปแบบอีเมลไม่ถูก|ใส่เบอร์โทร|อย่างน้อย 8 ตัว/g));
await p.goto('http://localhost:4000/login?error=access_denied&error_description=Unsupported+provider%3A+provider+is+not+enabled', { waitUntil: 'networkidle' });
await p.waitForTimeout(800);
out.push('oauth error shown: ' + (await body()).includes('ช่องทางนี้ยังไม่เปิดใช้'));
out.push('errors: ' + JSON.stringify(errs.filter(e => !e.includes('status of 400')).slice(0, 5)));
console.log(out.join('\n'));
await b.close();
